#!/usr/bin/env python3
"""Generate .github/workflows/pr-safety-ci.yml from the Full CI and offline-contracts steps.

PR Safety CI (Owner decision 2026-11-23) runs on every pull request under the fixed
check name "PR Safety CI". Its steps are the Full CI steps, copied byte for byte,
plus the offline-contracts steps:

* always-on steps run unconditionally (their own ``if`` is kept);
* selectable steps run only when scripts/ci/impact.py selects them for the
  changed files (``if: contains(fromJSON(steps.impact.outputs.selected), '<id>')``);
* Full-CI-only steps (``full_only`` in the map) are not copied.

The last step checks that exactly the selected and always-on steps ran and passed
and every other copied step was skipped. ``--check`` fails when the committed
workflow differs from what this generates, so a Full CI change cannot leave PR
Safety CI stale. Offline; no network.
"""
import argparse
import difflib
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import impact  # noqa: E402

HEADER = """# GENERATED by scripts/ci/pr_safety_workflow.py from {full} and
# {contracts}; do not edit by hand. Regenerate with
#   python3 scripts/ci/pr_safety_workflow.py --write
# PR Safety CI (Owner decision 2026-11-23) runs on every pull request to main under the
# fixed check name "PR Safety CI". The impact step maps the changed files to Full CI steps
# (scripts/ci/impact_map.json) and fails closed on unmapped paths; selected steps run
# exactly as in Full CI. PR Safety CI PASS is never Full CI PASS.
name: PR Safety CI

on:
  pull_request:
    branches: [main]

permissions:
  contents: read

# Runs never cancel each other (Owner, 2026-11-18): one run of this workflow at a time;
# never push to a pull request while its run is queued or in progress.
concurrency:
  group: ${{{{ github.workflow }}}}
  cancel-in-progress: false

jobs:
  {job}:
    name: {job_name}
    runs-on: ubuntu-24.04
    timeout-minutes: {timeout}
    defaults:
      run:
        shell: bash
    env:
{env}
    steps:
      - name: Check out the pull request merge commit with full history
        id: checkout
        uses: {checkout}
        with:
          persist-credentials: false
          fetch-depth: 0

      - name: Map changed files to the impacted Full CI steps (fail closed)
        id: impact
        env:
          EVENT_HEAD_SHA: ${{{{ github.event.pull_request.head.sha }}}}
        run: |
          set -euo pipefail
          python3 scripts/ci/impact.py select --event-head "$EVENT_HEAD_SHA" --report "$RUNNER_TEMP/pr-safety-impact.json" --github

      - name: Check changed files parse and add no whitespace errors
        id: changed_files
        run: |
          set -euo pipefail
          python3 scripts/ci/safety_checks.py changed --base HEAD^1 --head HEAD
"""

FOOTER = """
      - name: Verify that exactly the selected and always-on steps ran and passed
        if: ${{ always() }}
        env:
          STEP_RESULTS: ${{ toJSON(steps) }}
        run: |
          set -euo pipefail
          python3 scripts/ci/impact.py verify --report "$RUNNER_TEMP/pr-safety-impact.json"
"""


def with_condition(raw, condition, step_id):
    lines = raw.split("\n")
    impact.require(lines[0].startswith("      - "), "step_layout:" + step_id)
    impact.require(not any(line.startswith("        if:") for line in lines), "selectable_step_has_own_if:" + step_id)
    return "\n".join([lines[0], "        if: " + condition] + lines[1:])


def with_id(raw, step_id):
    lines = raw.split("\n")
    impact.require(not any(line.startswith("        id:") for line in lines), "contracts_step_has_id:" + step_id)
    return "\n".join([lines[0], "        id: " + step_id] + lines[1:])


def generate(tree=None):
    tree = tree or impact.Tree()
    mapping = impact.load_map(tree)
    steps = impact.Steps(tree, mapping)
    data, _full = impact.workflow_steps(tree, mapping["full_ci"]["workflow"], mapping["full_ci"]["job"])
    job = data["jobs"][mapping["full_ci"]["job"]]
    checkout = steps.by_id["checkout"]["uses"]
    impact.require(checkout and checkout.startswith("actions/checkout@"), "full_ci_checkout_missing")
    full_text = tree.read(mapping["full_ci"]["workflow"])
    pin = next(line.split("uses: ", 1)[1] for line in full_text.split("\n") if line.strip().startswith("uses: " + checkout))
    always, full_only = set(mapping["steps"]["always"]), set(mapping["steps"]["full_only"])
    body = []
    final = None
    for step in steps.full:
        if step["id"] in full_only:
            continue
        if step["id"] in always:
            block = step["raw"]
        else:
            block = with_condition(step["raw"], "${{ contains(fromJSON(steps.impact.outputs.selected), '%s') }}" % step["id"], step["id"])
        if step["id"] == "storage_final":
            final = block
            continue
        body.append(block)
    for step in steps.contracts:
        block = with_id(step["raw"], step["id"])
        body.append(with_condition(block, "${{ contains(fromJSON(steps.impact.outputs.selected), '%s') }}" % step["id"], step["id"]))
    impact.require(final is not None, "storage_final_missing")
    body.append(final)
    lines = full_text.split("\n")
    start = lines.index("  " + mapping["full_ci"]["job"] + ":")
    env_at = next(index for index in range(start, len(lines)) if lines[index] == "    env:")
    env_lines = []
    for line in lines[env_at + 1:]:
        if not line.startswith("      "):
            break
        env_lines.append(line)
    impact.require(len(env_lines) == len(job["env"]), "full_ci_job_env_layout")
    env = "\n".join(env_lines)
    header = HEADER.format(full=mapping["full_ci"]["workflow"], contracts=mapping["contracts"]["workflow"],
                           job=mapping["pr_safety"]["job"], job_name=mapping["pr_safety"]["job_name"],
                           timeout=mapping["pr_safety"]["timeout_minutes"], env=env, checkout=pin)
    return header + "\n" + "\n\n".join(body) + "\n" + FOOTER


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    try:
        tree = impact.Tree()
        expected = generate(tree)
        target = impact.REPO / impact.load_map(tree)["pr_safety"]["workflow"]
    except impact.ImpactError as error:
        print("PR Safety workflow generation failed closed: " + str(error), file=sys.stderr)
        return 1
    if args.write:
        target.write_text(expected, encoding="utf-8")
        print("wrote", target.relative_to(impact.REPO))
        return 0
    actual = target.read_text(encoding="utf-8") if target.is_file() else ""
    if actual != expected:
        sys.stderr.writelines(difflib.unified_diff(actual.splitlines(True), expected.splitlines(True), "committed", "generated", n=1))
        print("PR Safety workflow is stale: run python3 scripts/ci/pr_safety_workflow.py --write", file=sys.stderr)
        return 1
    print(json.dumps({"status": "passed", "check": "pr-safety-workflow-generated"}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
